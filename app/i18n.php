function localeCode(): string {
 $supported=['en','ms','zh-CN','zh-TW'];
 $choice=$_GET['lang']??null;
 if(is_string($choice) && in_array($choice,$supported,true))$_SESSION['locale']=$choice;
 $locale=$_SESSION['locale']??'en';
 return is_string($locale) && in_array($locale,$supported,true)?$locale:'en';
}
function localeName(?string $code=null): string {
 $names=['en'=>'English','ms'=>'Bahasa Melayu','zh-CN'=>'简体中文','zh-TW'=>'繁體中文'];
 return $names[$code??localeCode()]??'English';
}
